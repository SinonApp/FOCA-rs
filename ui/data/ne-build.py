#!/usr/bin/env python3
"""Builds country outlines for the 3D globe (/p/map) from Natural Earth (public domain).

    curl -sSLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
    curl -sSLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
    python3 ui/data/ne-build.py ne_110m_admin_0_countries.geojson ui/data/ne110.js 20 0.03
    python3 ui/data/ne-build.py ne_50m_admin_0_countries.geojson ui/data/ne50.js 100 0.012

Only the (Russian) name, ISO code and geometry are kept. Rings are simplified (Douglas-Peucker, tolerance in
degrees), coordinates are quantized (×q) and delta-encoded. The output is a JS file (window.FOCA_NE[...]) loaded
via a <script> tag, so it works from file:// without fetch or network access.
Format: { q, c: [[name, iso2, [ring, …]], …] }, ring = [lon0, lat0, dlon1, dlat1, …] in units of 1/q degree.
"""
import json, sys


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        n = (dx * dx + dy * dy) ** 0.5 or 1e-12
        best, bi = -1, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n if (dx or dy) else ((x - x1) ** 2 + (y - y1) ** 2) ** 0.5
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def main(src, dst, q, tol):
    q, tol = int(q), float(tol)
    gj = json.load(open(src, encoding="utf-8"))
    out = []
    for f in gj["features"]:
        p, g = f["properties"], f["geometry"]
        if not g:
            continue
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        rings = []
        for poly in polys:
            for ri, ring in enumerate(poly):
                if ri > 0:
                    continue  # holes (lakes/enclaves) are not needed on the globe
                r = dp(ring, tol)
                qp = []
                for x, y in r:
                    t = (round(x * q), round(y * q))
                    if not qp or qp[-1] != t:
                        qp.append(t)
                if len(qp) < 4:
                    continue
                enc, px, py = [], 0, 0
                for i, (x, y) in enumerate(qp):
                    enc += [x, y] if i == 0 else [x - px, y - py]
                    px, py = x, y
                rings.append(enc)
        if not rings:
            continue
        iso = p.get("ISO_A2_EH") or p.get("ISO_A2") or ""
        if iso == "-99":
            iso = ""
        out.append([p.get("NAME_RU") or p.get("NAME") or "", iso, rings])
    key = "n110" if "110" in dst else "n50"
    js = "/* Natural Earth admin-0 countries (public domain, naturalearthdata.com); generated by ui/data/ne-build.py */\n"
    js += "(window.FOCA_NE = window.FOCA_NE || {})." + key + " = " + json.dumps({"q": q, "c": out}, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open(dst, "w", encoding="utf-8").write(js)
    print(dst, len(out), "countries,", len(js.encode()) // 1024, "KB")


if __name__ == "__main__":
    main(*sys.argv[1:5])
