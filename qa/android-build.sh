#!/usr/bin/env bash
# Builds the Android app for the `foss` and `play` flavors without the Tauri CLI.
#
# `npx tauri android build` does not know the product flavors, and the Tauri `rustBuild*`
# Gradle tasks only work inside a running `tauri android build` (they ask the CLI over
# `.tauri/cli-options-server.json`). This script does what the CLI would do:
#   1. cargo builds libfoca_rs_lib.so for aarch64 with the environment that makes the
#      tauri/wry build scripts write the generated Android files (tauri.settings.gradle,
#      app/tauri.build.gradle.kts, app/proguard-tauri.pro, generated/*.kt);
#   2. writes app/tauri.properties (version) and assets/tauri.conf.json;
#   3. copies the .so into jniLibs/arm64-v8a;
#   4. runs Gradle with the Tauri Rust tasks excluded.
#
# Usage:
#   bash qa/android-build.sh kotlin     # cargo check + Kotlin compile of both flavors (no APK)
#   bash qa/android-build.sh apk        # release .so + unsigned universal{Foss,Play}Release APKs
# Environment: NDK linkers for aarch64-linux-android (CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER
# or NDK_HOME), ANDROID_HOME, JDK 17+. Signing is not done here.
set -euo pipefail
MODE=${1:-apk}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
GEN=$ROOT/src-tauri/gen/android
PKG=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["identifier"])' "$ROOT/src-tauri/tauri.conf.json")
KT_OUT=$GEN/app/src/main/java/${PKG//.//}/generated
TARGET=aarch64-linux-android
TARGET_DIR=${CARGO_TARGET_DIR:-$ROOT/target}

if [ -z "${CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER:-}" ] && [ -n "${NDK_HOME:-}" ]; then
  TC=$NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin
  export CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER=$TC/aarch64-linux-android24-clang
  export CC_aarch64_linux_android=$TC/aarch64-linux-android24-clang
  export AR_aarch64_linux_android=$TC/llvm-ar
fi

mkdir -p "$KT_OUT"
export TAURI_ANDROID_PROJECT_PATH=$GEN
export TAURI_ANDROID_PACKAGE_UNESCAPED=$PKG
export WRY_ANDROID_PACKAGE=$PKG
export WRY_ANDROID_LIBRARY=foca_rs_lib
export WRY_ANDROID_KOTLIN_FILES_OUT_DIR=$KT_OUT

cd "$ROOT"
case "$MODE" in
  kotlin) cargo check --target $TARGET -p foca-rs --lib ;;
  apk) cargo build --release --target $TARGET -p foca-rs --lib ;;
  *) echo "usage: $0 kotlin|apk" >&2; exit 2 ;;
esac
for f in tauri.settings.gradle app/tauri.build.gradle.kts app/proguard-tauri.pro; do
  [ -f "$GEN/$f" ] || { echo "FAIL: $f was not generated by the tauri build script" >&2; exit 1; }
done
ls "$KT_OUT"/TauriActivity.kt "$KT_OUT"/WryActivity.kt > /dev/null

# Version as the Tauri CLI writes it: bundle.android.versionCode when set, else 2.0.0 -> 2000000
# (the pre-release part is ignored, so pre-releases need an explicit versionCode).
python3 - "$ROOT/src-tauri/tauri.conf.json" "$GEN/app/tauri.properties" <<'PY'
import json, sys
conf = json.load(open(sys.argv[1]))
v = conf["version"]
ma, mi, pa = (int(x) for x in v.split("-")[0].split(".")[:3])
code = conf.get("bundle", {}).get("android", {}).get("versionCode") or ma * 1000000 + mi * 1000 + pa
open(sys.argv[2], "w").write(
    "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n"
    f"tauri.android.versionName={v}\ntauri.android.versionCode={code}"
)
PY
mkdir -p "$GEN/app/src/main/assets"
python3 -c 'import json,sys; json.dump(json.load(open(sys.argv[1])), open(sys.argv[2], "w"), separators=(",", ":"))' \
  "$ROOT/src-tauri/tauri.conf.json" "$GEN/app/src/main/assets/tauri.conf.json"

GRADLE_ARGS=(--no-daemon -PtargetList=aarch64 -ParchList=arm64 -PabiList=arm64-v8a
  -x rustBuildArm64Release -x rustBuildUniversalRelease)
cd "$GEN"
if [ "$MODE" = kotlin ]; then
  ./gradlew "${GRADLE_ARGS[@]}" :app:compileUniversalFossReleaseKotlin :app:compileUniversalPlayReleaseKotlin
  exit 0
fi

SO=$TARGET_DIR/$TARGET/release/libfoca_rs_lib.so
JNI=$GEN/app/src/main/jniLibs/arm64-v8a
mkdir -p "$JNI"
# Locally the .so in jniLibs may be a symlink to the target file already.
if [ "$(readlink -f "$JNI/libfoca_rs_lib.so" 2>/dev/null)" != "$(readlink -f "$SO")" ]; then
  rm -f "$JNI/libfoca_rs_lib.so"
  cp "$SO" "$JNI/libfoca_rs_lib.so"
fi
./gradlew "${GRADLE_ARGS[@]}" assembleUniversalFossRelease assembleUniversalPlayRelease
ls -la app/build/outputs/apk/universalFoss/release/*.apk app/build/outputs/apk/universalPlay/release/*.apk
