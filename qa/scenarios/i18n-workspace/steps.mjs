// Workspace screens in EN / UK: no hard-coded Russian UI text.
// With the default ru-RU locale (qa/run-all.sh) the scenario switches the UI to EN and then UK itself and
// restores the setting afterwards. A single language can be checked through the "auto" setting:
//   qa/shoot.sh --routes none --locale en-US --out $PWD/qa/out/i18n-workspace-en --steps $PWD/qa/scenarios/i18n-workspace/steps.mjs
//   qa/shoot.sh --routes none --locale uk-UA --out $PWD/qa/out/i18n-workspace-uk --steps $PWD/qa/scenarios/i18n-workspace/steps.mjs
// EN: visible text, aria-label/title/placeholder must have no Cyrillic, except demo data values (every
// Cyrillic word of the text node occurs in the demo backend state). UK: no Russian-only letters (ы э ъ ё)
// outside data values.
import fs from "node:fs";

const ROUTES = [
  "/projects",
  "/p/overview",
  "/p/search",
  "/p/data/docs",
  "/p/data/people",
  "/p/data/emails",
  "/p/data/hosts",
  "/p/data/certs",
  "/p/data/mailpol",
  "/p/data/saas",
  "/p/data/software",
  "/p/data/os",
  "/p/data/secrets",
  "/p/data/paths",
  "/p/data/printers",
  "/p/map",
  "/p/timeline",
  "/p/monitor",
  "/p/diff",
  "/p/ai",
  "/p/preflight",
  "/settings/plugins",
  "/settings/ai",
  "/help",
  "/welcome",
];

// Demo sample data (plugin manifests, GPS countries …) is generated by the demo backend, not by UI code.
const DEMO_SRC = fs.readFileSync(new URL("../../../ui/js/demo-backend.js", import.meta.url), "utf8");

export default async (page, { out, W, go, checkText, errs }) => {
  const fails = [];
  let oks = 0;
  await go("/projects");
  await page.evaluate(src => {
    window.__focaDemoSrc = src;
  }, DEMO_SRC);
  const lang0 = await page.evaluate(() => FOCA.i18n.lang());
  const setting0 = await page.evaluate(() => FOCA.i18n.setting());
  let lang = lang0;
  let bad = null;
  const scan = label =>
    page.evaluate(
      ([src, label]) => {
        const re = new RegExp(src);
        const st = window.FOCA_DEMO_BACKEND ? window.FOCA_DEMO_BACKEND._state() : {};
        // Help articles come from locales/<lang>/help.json (not UI strings).
        const blob = JSON.stringify([st, FOCA.projects, FOCA.db || null, FOCA.i18n.help()]) + (window.__focaDemoSrc || "");
        // Redaction tokens of the AI summary ([СЕКРЕТ], [ФИО] …) are literal markers the core inserts.
        const isData = t => {
          t = t.replace(/\[(КЛИЕНТ-ДОМЕН|КЛИЕНТ|ФИО|EMAIL|СЕКРЕТ|IP-ВНУТР)\]/g, "");
          // Only the offending words must be data values (a text node may mix UI text and data).
          const words = (t.match(/[А-Яа-яЁёІіЇїЄєҐґ'’]+/g) || []).filter(w => re.test(w));
          return words.every(w => blob.includes(w));
        };
        const hits = [];
        const roots = [
          document.querySelector("#app") || document.body,
          ...document.querySelectorAll(".sheet, .snack, #tb, .topbar"),
        ];
        const seen = new Set();
        for (const root of roots) {
          if (!root || seen.has(root)) continue;
          seen.add(root);
          const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
          for (let n = w.nextNode(); n; n = w.nextNode()) {
            const el = n.parentElement;
            // Avatars show initials derived from people's names.
            if (!el || el.closest("script,style,[hidden],.avatar") || !el.getClientRects().length) continue;
            const t = n.nodeValue.trim();
            if (t && re.test(t) && !isData(t)) hits.push(t.slice(0, 80));
          }
          for (const el of root.querySelectorAll("[aria-label],[title],[placeholder]"))
            for (const a of ["aria-label", "title", "placeholder"]) {
              const t = (el.getAttribute(a) || "").trim();
              if (t && re.test(t) && !isData(t)) hits.push(`@${a}: ${t.slice(0, 80)}`);
            }
        }
        return [...new Set(hits)].slice(0, 12).map(h => `${label}: ${h}`);
      },
      [bad, label],
    );
  const check = async (label, shot) => {
    await page.waitForTimeout(300);
    await checkText(label);
    if (shot) await page.screenshot({ path: `${out}/i18n_${lang}_${shot}_${W}.png` });
    if (!bad) return;
    const hits = await scan(label);
    if (hits.length) fails.push(...hits);
    else oks++;
  };
  const visit = async r => {
    await page.evaluate(r => FOCA.go(r), r);
    await check(r, r.replace(/[^\w]+/g, "_").replace(/^_|_$/g, ""));
  };
  const runLang = async () => {
    await page.evaluate(() => FOCA.go("/projects"));
    // Projects list + its sheets.
    await check("/projects", "projects");
    await page.evaluate(() => FOCA.api.project_open("contoso"));
    for (const r of ROUTES.slice(1)) await visit(r);
    // Entity cards and the graph (ids come from the data screens).
    for (const seg of ["people", "hosts", "software", "emails", "printers", "paths"]) {
      await page.evaluate(s => FOCA.go(`/p/data/${s}`), seg);
      await page.waitForTimeout(250);
      const p = await page.evaluate(() => {
        const el = document.querySelector('[data-act^="dt-nav:/p/entity/"]');
        return el ? el.getAttribute("data-act").slice(7) : null;
      });
      if (p) await visit(decodeURI(p));
    }
    const plug = await page.evaluate(() => {
      FOCA.go("/settings/plugins");
      const el = document.querySelector('[data-act*="/settings/plugin/"]');
      return el ? el.getAttribute("data-act").replace(/^[^:]*:/, "") : null;
    });
    if (plug) await visit(plug);
    const art = await page.evaluate(() => {
      FOCA.go("/help");
      const el = document.querySelector('[data-act*="/help/"]');
      return el ? el.getAttribute("data-act").replace(/^[^:]*:/, "") : null;
    });
    if (art) await visit(art);
    // Project actions sheet, import and export sheets.
    await page.evaluate(() => FOCA.go("/projects"));
    for (const act of [
      "pj-menu:contoso",
      "pj-import-enc",
      "pj-export:contoso",
      "pj-props:contoso",
      "pj-del:contoso",
      "pj-archive-list",
    ]) {
      const ok = await page.evaluate(a => {
        const [n, arg] = a.split(":");
        if (!FOCA.actions[n]) return false;
        FOCA.actions[n](arg, document.body, new Event("click"));
        return true;
      }, act);
      if (!ok) continue;
      await check(`sheet ${act}`, `sheet_${act.replace(/\W+/g, "_")}`);
      await page.evaluate(() => FOCA.closeSheet && FOCA.closeSheet());
      await page.waitForTimeout(250);
    }
  };
  for (const l of lang0 === "ru" ? ["en", "uk"] : [lang0]) {
    if (l !== lang0)
      await page.evaluate(async l => {
        await FOCA.i18n.load(l);
        await FOCA.api.project_open("contoso");
      }, l);
    lang = await page.evaluate(() => FOCA.i18n.lang());
    bad = lang === "en" ? "[А-Яа-яЁёІіЇїЄєҐґ]" : lang === "uk" ? "[ЫыЭэЪъЁё]" : null;
    if (lang !== l) fails.push(`language ${l} not applied (got ${lang})`);
    await runLang();
  }
  if (lang0 === "ru") await page.evaluate(s => FOCA.i18n.load(s), setting0);
  for (const f of fails) console.error(`  FAIL ${f}`);
  console.error(`i18n-workspace: ${oks} OK, ${fails.length} FAIL`);
  if (fails.length) errs.push(`i18n-workspace: ${fails.length} untranslated strings`);
};
