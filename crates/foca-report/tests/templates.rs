#[test]
fn extra_templates_content() {
    let snap = &fixture().snap;
    let get = |tpl, lang| text(&build(snap, &tpl_opts(tpl, lang, ReportFormat::Html)));
    // Executive: one page, risk score, top five, three actions, no technical tables.
    let ex = get(Template::Executive, Lang::Uk);
    assert!(ex.contains("Головні знахідки") && ex.contains("Три першочергові дії"));
    assert!(!ex.contains("<table"), "executive has no tables");
    let ol = ex
        .split("<ol>")
        .nth(2)
        .unwrap()
        .split("</ol>")
        .next()
        .unwrap();
    assert_eq!(ol.matches("<li>").count(), 3);
    let top = ex
        .split("<ol>")
        .nth(1)
        .unwrap()
        .split("</ol>")
        .next()
        .unwrap();
    assert!(top.matches("<li>").count() <= 5);
    // Compliance: standards columns, НД ТЗІ and ISO summaries, disclaimer.
    let co = get(Template::Compliance, Lang::Ru);
    for s in [
        "MITRE ATT&amp;CK",
        "CWE-212",
        "A.8.12",
        "НД ТЗІ 2.5-004-99",
        "3.7-003-05",
        "Оговорка аудитора",
    ] {
        assert!(co.contains(s), "compliance lacks {s}");
    }
    assert!(co.contains("6.1.2.5") && co.contains("WSTG"));
    // Lab: all sections and the blank sign-off fields.
    let lab = get(Template::Lab, Lang::Uk);
    for s in [
        "1. Мета",
        "2. Методика",
        "3. Вихідні дані",
        "4. Хід дослідження",
        "5. Таблиця знахідок",
        "6. Висновки та рекомендації",
        "Виконав",
        "Перевірив",
    ] {
        assert!(lab.contains(s), "lab lacks {s}");
    }
    assert!(lab.contains("<dl class=\"sign\"><dt>Виконав</dt><dd><small>"));
    let en = text(&build(
        snap,
        &tpl_opts(Template::Lab, Lang::En, ReportFormat::Md),
    ));
    assert!(en.contains("## 6. Conclusions and recommendations") && en.contains("Performed by"));
}

#[test]
fn full_template_is_unchanged_by_the_template_parameter() {
    let snap = &fixture().snap;
    for fmt in [ReportFormat::Html, ReportFormat::Md] {
        let base = build(snap, &opts(fmt));
        let mut v = serde_json::to_value(foca_report::normalized_opts(&opts(fmt))).unwrap();
        v["template"] = "full".into();
        let o = ReportOptions {
            sections: Sections::all(),
            company: "ТОВ «Кібер Аудит»".into(),
            secrets: SecretMode::Hide,
            ..ReportOptions::from_ui(&v)
        };
        assert_eq!(o.tpl, Template::Full);
        assert_eq!(build(snap, &o).bytes, base.bytes);
    }
    // `template` takes precedence over the legacy `tpl_id`.
    let o = ReportOptions::from_ui(&serde_json::json!({ "template": "lab", "tpl_id": "brief" }));
    assert_eq!(o.tpl, Template::Lab);
}

#[test]
fn extra_templates_escape_everything() {
    let snap = hostile();
    for (tpl, _) in EXTRA_TEMPLATES {
        for lang in [Lang::Uk, Lang::Ru] {
            let h = text(&build(&snap, &tpl_opts(tpl, lang, ReportFormat::Html)));
            assert_safe_html(&h);
            assert!(h.contains("&lt;/title&gt;&lt;script&gt;alert(1)&lt;/script&gt;"));
            let md = text(&build(&snap, &tpl_opts(tpl, lang, ReportFormat::Md)));
            assert!(
                !raw_md_tag(&md, "<script") && !raw_md_tag(&md, "<img"),
                "{tpl:?}"
            );
            for line in md.lines().filter(|l| l.starts_with('|')) {
                let raw = line
                    .match_indices('|')
                    .filter(|(i, _)| *i == 0 || &line[i - 1..*i] != "\\")
                    .count();
                assert!(raw >= 2, "{line}");
            }
        }
    }
}

#[test]
fn report_templates_catalog() {
    for lang in [Lang::Uk, Lang::Ru, Lang::En] {
        let v = foca_report::report_templates(lang);
        let ids: Vec<&str> = v
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t["id"].as_str().unwrap())
            .collect();
        assert_eq!(ids, ["full", "executive", "compliance", "lab"]);
        for t in v.as_array().unwrap() {
            assert!(!t["title"].as_str().unwrap().is_empty());
            assert!(!t["description"].as_str().unwrap().is_empty());
            assert!(Template::parse(t["id"].as_str().unwrap()).is_some());
        }
    }
}

#[test]
fn ai_summary_section_labelled_escaped_and_optional() {
    let snap = &fixture().snap;
    // HTML: own section before the summary, labelled, everything escaped, in the TOC.
    let h = text(&build(snap, &with_ai(ReportFormat::Html, Lang::En, true)));
    assert_safe_html(&h);
    assert!(h.contains("<section id=\"ai-summary\">\n<h2>Executive summary (AI-assisted)</h2>"));
    assert!(h.contains("href=\"#ai-summary\""));
    assert!(h.contains("Generated by a cloud AI model (anthropic · claude-x, 2026-11-25)"));
    assert!(h.contains("&lt;script&gt;") && !h.contains("<script>alert"));
    assert!(h.contains("<h4>Key risks</h4>") && h.contains("<li>"));
    assert!(h.find("id=\"ai-summary\"").unwrap() < h.find("id=\"summary\"").unwrap());
    // Markdown: no raw tags, section shape pinned by a golden.
    let md = text(&build(snap, &with_ai(ReportFormat::Md, Lang::En, true)));
    assert!(!raw_md_tag(&md, "<script") && !raw_md_tag(&md, "<img"));
    golden(
        "ai-summary.en.md",
        &md_section(&md, "## Executive summary (AI-assisted)"),
    );
    let ru = text(&build(snap, &with_ai(ReportFormat::Md, Lang::Ru, true)));
    assert!(ru.contains("## Резюме для руководства (подготовлено с помощью ИИ)"));
    // DOCX: heading, disclaimer and text in document.xml.
    let d = build(snap, &with_ai(ReportFormat::Docx, Lang::Uk, true));
    let mut ar = zip::ZipArchive::new(std::io::Cursor::new(d.bytes)).unwrap();
    let mut xml = String::new();
    ar.by_name("word/document.xml")
        .unwrap()
        .read_to_string(&mut xml)
        .unwrap();
    assert!(xml.contains("Резюме для керівництва (підготовлено за допомогою ШІ)"));
    assert!(xml.contains("FOCA-rs не перевіряє цей текст"));
    assert!(xml.contains("Rotate keys.") && !xml.contains("<script>"));
    // The executive brief (own template) carries it too.
    let ex = ReportOptions {
        tpl: Template::Executive,
        sections: Sections::for_template(Template::Executive),
        ..with_ai(ReportFormat::Html, Lang::En, true)
    };
    let h = text(&build(snap, &ex));
    assert_safe_html(&h);
    assert!(h.contains("<h2>Executive summary (AI-assisted)</h2>") && h.contains("Rotate keys."));
    // Switched off or absent: no section in any format.
    for fmt in [ReportFormat::Html, ReportFormat::Md] {
        let off = text(&build(snap, &with_ai(fmt, Lang::En, false)));
        assert!(
            !off.contains("AI-assisted") && !off.contains("Rotate keys"),
            "{fmt:?}"
        );
        let none = text(&build(snap, &opts(fmt)));
        assert!(!none.contains("AI-assisted"), "{fmt:?}");
    }
}

#[test]
fn ai_summary_option_parsing_keeps_raw_clean() {
    let o = ReportOptions::from_ui(&serde_json::json!({
        "fmt": "md",
        "ai_summary_data": { "text": "Summary", "provider": "openai", "model": "m" }
    }));
    assert!(o.include_ai_summary);
    assert_eq!(
        o.ai_summary.as_ref().map(|a| a.text.as_str()),
        Some("Summary")
    );
    assert!(
        o.raw.get("ai_summary_data").is_none(),
        "summary text must not land in the report record"
    );
    let o = ReportOptions::from_ui(&serde_json::json!({ "ai_summary": false,
        "ai_summary_data": { "text": "  " } }));
    assert!(!o.include_ai_summary && o.ai_summary.is_none());
}
